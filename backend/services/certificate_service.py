from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from config import settings


class CertificateService:
    """Produces PDF proof-of-ownership certificates for stored ideas."""

    def __init__(self) -> None:
        self.output_dir = Path(settings.certificate_output_dir)
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def generate(
        self,
        *,
        idea_name: str,
        owner: str,
        date_text: str,
        innovation_score: float,
        similarity_score: float | None = None,
        timestamp_text: str | None = None,
    ) -> Path:
        """Render a polished certificate PDF and return the generated file path."""
        safe_name = "".join(character if character.isalnum() else "_" for character in idea_name.lower()).strip("_")
        path = self.output_dir / f"{safe_name or 'idea'}_certificate.pdf"

        document = SimpleDocTemplate(
            str(path),
            pagesize=letter,
            leftMargin=0.8 * inch,
            rightMargin=0.8 * inch,
            topMargin=0.8 * inch,
            bottomMargin=0.8 * inch,
        )
        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            "CertificateTitle",
            parent=styles["Title"],
            fontName="Helvetica-Bold",
            fontSize=24,
            leading=30,
            textColor=colors.HexColor("#0f172a"),
            alignment=1,
        )
        subtitle_style = ParagraphStyle(
            "CertificateSubtitle",
            parent=styles["BodyText"],
            fontName="Helvetica",
            fontSize=11,
            leading=18,
            textColor=colors.HexColor("#475569"),
            alignment=1,
        )
        footer_style = ParagraphStyle(
            "CertificateFooter",
            parent=styles["BodyText"],
            fontName="Helvetica-Oblique",
            fontSize=10,
            leading=16,
            textColor=colors.HexColor("#64748b"),
            alignment=1,
        )

        # The certificate is composed as a simple story so it can render consistently in local and Docker environments.
        elements = [
            Spacer(1, 18),
            Paragraph("AI Idea Authenticity & Innovation Platform", subtitle_style),
            Spacer(1, 14),
            Paragraph("Innovation Ownership Certificate", title_style),
            Spacer(1, 16),
            Paragraph(
                "This document certifies that the idea below was registered and assessed for originality by the platform.",
                subtitle_style,
            ),
            Spacer(1, 28),
        ]

        # These are the required ownership details the user asked to include in the PDF.
        info_table = Table(
            [
                ["Idea Name", idea_name],
                ["Owner", owner],
                ["Date", date_text],
                ["Innovation Score", f"{innovation_score}/100"],
                ["Similarity Score", f"{similarity_score}/100" if similarity_score is not None else "Not recorded"],
                ["Timestamp", timestamp_text or date_text],
            ],
            colWidths=[140, 340],
        )
        info_table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#e2e8f0")),
                    ("BACKGROUND", (1, 0), (1, -1), colors.white),
                    ("TEXTCOLOR", (0, 0), (-1, -1), colors.HexColor("#0f172a")),
                    ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
                    ("FONTNAME", (1, 0), (1, -1), "Helvetica"),
                    ("FONTSIZE", (0, 0), (-1, -1), 12),
                    ("GRID", (0, 0), (-1, -1), 1, colors.HexColor("#cbd5e1")),
                    ("BOX", (0, 0), (-1, -1), 1.5, colors.HexColor("#94a3b8")),
                    ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                    ("PADDING", (0, 0), (-1, -1), 12),
                ]
            )
        )

        elements.extend(
            [
                info_table,
                Spacer(1, 24),
                Paragraph(
                    "Generated as proof of idea ownership and innovation scoring for the registered submission.",
                    subtitle_style,
                ),
                Spacer(1, 32),
                Paragraph("Generated by AI Idea Authenticity & Innovation Platform", footer_style),
            ]
        )
        document.build(elements)
        return path
